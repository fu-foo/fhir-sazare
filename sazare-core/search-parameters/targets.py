#!/usr/bin/env python3
"""Generate targets.tsv: the resource types each R4 reference search parameter
may point to.

  curl -sfLO https://hl7.org/fhir/R4/search-parameters.json
  python3 sazare-core/search-parameters/targets.py search-parameters.json > sazare-core/search-parameters/targets.tsv

One line per (base resource type, parameter): base, code, the target types
(comma-separated). A chain written without a type (`subject.family`) is
resolved with it: the targets that have the next parameter.

Source: HL7 FHIR R4 (4.0.1), CC0-1.0 (see NOTICE.md).
"""
import json
import sys

bundle = json.load(open(sys.argv[1]))
rows = set()
for entry in bundle["entry"]:
    sp = entry["resource"]
    if sp.get("type") != "reference" or not sp.get("target"):
        continue
    for base in sp.get("base", []):
        if base in ("Resource", "DomainResource"):
            continue
        rows.add((base, sp["code"], ",".join(sorted(set(sp["target"])))))
print("# FHIR R4 4.0.1 reference search parameter targets; CC0-1.0. Generated by targets.py: do not edit.")
for row in sorted(rows):
    print("\t".join(row))
