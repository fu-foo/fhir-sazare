#!/usr/bin/env python3
"""Generate r4.tsv from the FHIR R4 search parameter definitions.

  curl -sfLO https://hl7.org/fhir/R4/search-parameters.json
  python3 sazare-core/search-parameters/generate.py search-parameters.json > sazare-core/search-parameters/r4.tsv

One line per (base resource type, parameter): base, code, type, expression.
Only the types sazare indexes (token, string, date, reference, number,
quantity); the
Resource-level parameters (_id, _tag, ...) are built in separately. The
registry adds these to the hand-written definitions for the parameters those
don't cover (see SearchParamRegistry::new).

Source: HL7 FHIR R4 (4.0.1), CC0-1.0 (see NOTICE.md).
"""
import json
import sys

TYPES = {"token", "string", "date", "reference", "number", "quantity"}


def branches(expr):
    """The top-level alternatives of `a | b | (c as T)` (not inside parentheses or quotes)."""
    out, depth, quote, cur = [], 0, False, ""
    for ch in expr:
        if ch == "'":
            quote = not quote
        elif not quote and ch == "(":
            depth += 1
        elif not quote and ch == ")":
            depth -= 1
        if ch == "|" and depth == 0 and not quote:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    out.append(cur.strip())
    return out


def for_base(expr, base):
    """Only the alternatives about `base`: the shared R4 parameters list up to
    32 resource types in one expression (`AllergyIntolerance.patient | ...`)."""
    mine = [b for b in branches(expr) if b.lstrip("(").startswith(base + ".")]
    return " | ".join(mine) if mine else expr
bundle = json.load(open(sys.argv[1]))
rows = set()
for entry in bundle["entry"]:
    sp = entry["resource"]
    if sp.get("type") not in TYPES or not sp.get("expression"):
        continue
    expr = " ".join(sp["expression"].split())
    for base in sp.get("base", []):
        if base in ("Resource", "DomainResource"):
            continue
        rows.add((base, sp["code"], sp["type"], for_base(expr, base)))
version = bundle.get("meta", {}).get("lastUpdated", "")
print(f"# FHIR R4 4.0.1 search parameters ({version}); CC0-1.0. Generated by generate.py: do not edit.")
for row in sorted(rows):
    print("\t".join(row))
